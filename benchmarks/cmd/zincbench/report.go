// cmdReport writes BENCHMARKS.md from a recorded run: both tiers' scores,
// every scenario's medians, and every scenario Zinc loses. Nothing in it is
// written by hand, so the published report always matches a run.
func cmdReport(s *Store, args []string) error {
	fs := newFlags("report")
	out := fs.String("o", "", "write to this file instead of standard output")
	_ = fs.Parse(args)
	run, err := s.resolveRun(fs.Arg(0))
	if err != nil {
		return err
	}
	w := io.Writer(os.Stdout)
	if *out != "" {
		f, err := os.Create(*out)
		if err != nil {
			return err
		}
		defer f.Close()
		w = f
	}
	return writeReport(w, run)
}

func writeReport(w io.Writer, run *Run) error {
	var b strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	release := run.Release
	if release == "" {
		release = "unreleased"
	}
	p("# Zinc Benchmarks\n\n")
	p("This report compares Zinc with Gin and Echo, and Zinc's routing with BunRouter and Chi. Every framework does the same work through its own idiomatic API, in process, and all five were measured together in one run. Lower is better.\n\n")
	p("It is generated by `zincbench report` from run `%s` (%s). Nothing in it is edited by hand.\n\n", run.ID, release)

	p("## Run information\n\n")
	p("- Date: `%s`\n", reportDate(run.CreatedAt))
	p("- Zinc commit: `%s`", run.Git.Short)
	if run.Git.Dirty {
		p(" (with uncommitted changes)")
	}
	p("\n- Rivals: %s\n", rivalList(run.Env.Rivals))
	p("- Go: `%s`\n", run.Env.Go)
	p("- Machine: `%s`\n", run.Env.CPU)
	p("- OS / architecture: `%s / %s`\n", run.Env.GOOS, run.Env.GOARCH)
	p("- Samples: `%d × %s` per scenario, for every framework\n", run.Env.Count, run.Env.Benchtime)
	p("- Measurement: median `ns/op` across the samples\n\n")

	p("## Summary\n\n")
	p("Zinc is scored in two tables. **Frameworks** is the headline: Gin and Echo, on every scenario. **Routers** puts Zinc's routing against two bare routers, BunRouter and Chi, on the routing scenarios they can run. A bare router does less per request than a framework, so the second table is a stricter test of the router alone.\n\n")
	p("The distance column is the geometric mean, over the table's scenarios, of how far each framework's median is above the fastest median in that scenario. 0%% would mean fastest everywhere.\n\n")
	for _, t := range tiers {
		fws := append([]string{"Zinc"}, t.Rivals...)
		names := tierScenarios(run, t)
		p("### %s (%d scenarios)\n\n", t.Name, len(names))
		p("| Framework | Fastest in | Distance from the fastest |\n| --- | ---: | ---: |\n")
		for _, fw := range fws {
			wins, geo := frameworkScore(run, names, fws, fw)
			name := fw
			if fw == "Zinc" {
				name = "**Zinc**"
			}
			p("| %s | %d / %d | +%.1f%% |\n", name, wins, len(names), geo)
		}
		p("\n")
	}

	for _, t := range tiers {
		fws := append([]string{"Zinc"}, t.Rivals...)
		names := tierScenarios(run, t)
		p("## %s: every scenario\n\n", t.Name)
		p("Median ns/op. The winner has the lowest median in the row.\n\n")
		p("| Benchmark | %s | Winner |\n| --- |%s --- |\n", strings.Join(fws, " | "), strings.Repeat(" ---: |", len(fws)))
		for _, name := range names {
			sc := run.Scenarios[name]
			cells := make([]string, len(fws))
			for i, fw := range fws {
				cells[i] = formatNS(median(sc[fw].NS))
			}
			p("| `%s` | %s | %s |\n", name, strings.Join(cells, " | "), fastest(sc, fws))
		}
		p("\n")
	}

	p("## Where Zinc is slower\n\n")
	p("Zinc's median against the fastest rival in the same table. A gap under 5%% is within the noise of one run: treat it as a tie.\n\n")
	for _, t := range tiers {
		fws := append([]string{"Zinc"}, t.Rivals...)
		type loss struct {
			name, rival string
			gap         float64
		}
		var losses []loss
		for _, name := range tierScenarios(run, t) {
			sc := run.Scenarios[name]
			z := median(sc["Zinc"].NS)
			best := fastest(sc, fws)
			if best == "Zinc" {
				continue
			}
			losses = append(losses, loss{name, best, (z/median(sc[best].NS) - 1) * 100})
		}
		sort.Slice(losses, func(i, j int) bool { return losses[i].gap > losses[j].gap })
		p("### %s: Zinc slower in %d\n\n", t.Name, len(losses))
		if len(losses) == 0 {
			p("Zinc is fastest in every scenario of this table.\n\n")
			continue
		}
		p("| Benchmark | Winner | Zinc slower by |\n| --- | --- | ---: |\n")
		for _, l := range losses {
			p("| `%s` | %s | %.1f%% |\n", l.name, l.rival, l.gap)
		}
		p("\n")
	}

	p("## Scope and reproducibility\n\n")
	p("The suite covers routing, misses, registration, route sets, binding, response helpers, static files, middleware and parallel dispatch. Every request pool holds 10,000 distinct paths, so no framework can answer a repeated URL from a cache, and each scenario first checks that every framework returns the same response. The upstream Gin routing suite is reported separately in [GIN_BENCHMARK.md](GIN_BENCHMARK.md); its counts must not be added to these.\n\n")
	p("To record a run and regenerate this report, from the benchmark module:\n\n")
	p("```bash\ncd benchmarks\ngo run ./cmd/zincbench record -release <version>\ngo run ./cmd/zincbench report -o ../BENCHMARKS.md latest\n```\n\n")
	p("Records live in `benchmarks/results/`, which git ignores. A release's runs are bundled with `zincbench bundle`.\n")

	_, err := io.WriteString(w, b.String())
	return err
}

// tierScenarios lists, in name order, the scenarios every framework in t ran.
func tierScenarios(run *Run, t Tier) []string {
	var names []string
	for name, sc := range run.Scenarios {
		if t.covers(sc) {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	return names
}

// frameworkScore is one framework's strict wins and geometric-mean distance
// from the fastest over names, among fws.
func frameworkScore(run *Run, names, fws []string, fw string) (int, float64) {
	wins, logs := 0, 0.0
	for _, name := range names {
		sc := run.Scenarios[name]
		mine := median(sc[fw].NS)
		best, strict := mine, true
		for _, other := range fws {
			if other == fw {
				continue
			}
			m := median(sc[other].NS)
			best = math.Min(best, m)
			if m <= mine {
				strict = false
			}
		}
		if strict {
			wins++
		}
		if best > 0 {
			logs += math.Log(mine / best)
		}
	}
	if len(names) == 0 {
		return 0, 0
	}
	return wins, (math.Exp(logs/float64(len(names))) - 1) * 100
}

// fastest names the framework with the lowest median; ties go to the first.
func fastest(sc Scenario, fws []string) string {
	best := fws[0]
	for _, fw := range fws[1:] {
		if median(sc[fw].NS) < median(sc[best].NS) {
			best = fw
		}
	}
	return best
}

func formatNS(v float64) string {
	switch {
	case v >= 1000:
		return groupThousands(strconv.FormatFloat(math.Round(v), 'f', 0, 64))
	case v >= 100:
		return strconv.FormatFloat(v, 'f', 1, 64)
	default:
		return strconv.FormatFloat(v, 'f', 2, 64)
	}
}

func groupThousands(s string) string {
	var b strings.Builder
	for i, r := range s {
		if i > 0 && (len(s)-i)%3 == 0 {
			b.WriteByte(',')
		}
		b.WriteRune(r)
	}
	return b.String()
}

func rivalList(rivals map[string]string) string {
	names := make([]string, 0, len(rivals))
	for name := range rivals {
		names = append(names, name)
	}
	sort.Strings(names)
	parts := make([]string, len(names))
	for i, name := range names {
		parts[i] = fmt.Sprintf("%s `%s`", name, rivals[name])
	}
	return strings.Join(parts, ", ")
}

func reportDate(createdAt string) string {
	if len(createdAt) >= 10 {
		return createdAt[:10]
	}
	return createdAt
}
